import test from 'node:test';
import assert from 'node:assert/strict';
import { once } from 'node:events';
import { randomUUID } from 'node:crypto';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { MysqlStore } from './store.ts';
import { UserAccounts } from './accounts.mjs';
import { AccessControl } from './access.mjs';
import { createApp } from './server.mjs';

test('真实数据库：注册登录、两用户隔离、会话绑定及管理员迁移旧记录', { skip: process.env.MYSQL_INTEGRATION !== '1' }, async t => {
  const database = process.env.MYSQL_TEST_DATABASE || `${process.env.MYSQL_DATABASE}_test`;
  assert.match(database, /_test$/, '隔离测试必须使用独立的 _test 数据库');
  const store = new MysqlStore({ ...process.env, MYSQL_DATABASE: database });
  await store.init();
  const accounts = new UserAccounts({ pool: store.pool });await accounts.init();
  const directory = await mkdtemp(join(tmpdir(), 'qinghe-users-'));
  const auth = await AccessControl.open(directory);
  const credentials = await readFile(join(directory, 'admin-credentials.txt'), 'utf8');
  const adminPassword = credentials.match(/管理员密码：(\S+)/)[1], code = credentials.match(/初始 AI 访问码：(\d{6})/)[1];
  let modelCalls = 0;
  const server = createApp({ store, accounts, auth, model: async () => { modelCalls++;return { configured: true, answer: '测试回答' }; } });
  server.listen(0, '127.0.0.1');await once(server, 'listening');
  const base = `http://127.0.0.1:${server.address().port}`;
  const post = (path, input, cookie = '', headers = {}) => fetch(base + path, { method: 'POST', headers: { 'Content-Type': 'application/json', Cookie: cookie, ...headers }, body: JSON.stringify(input) });
  const get = (path, cookie = '') => fetch(base + path, { headers: { Cookie: cookie } });
  const cookies = response => response.headers.getSetCookie().filter(c => !c.includes('Max-Age=0')).map(c => c.split(';')[0]).join('; ');
  const names = ['a', 'b'].map(prefix => `${prefix}_${randomUUID().replaceAll('-', '').slice(0,20)}`);
  const ids = [], noteIds = [];
  t.after(async () => {
    server.close();server.closeAllConnections();
    for (const id of noteIds) await store.pool.execute('DELETE FROM readings WHERE id=?', [id]);
    for (const id of ids) await store.pool.execute('DELETE FROM users WHERE id=?', [id]);
    await store.close();await rm(directory, { recursive: true, force: true });
  });
  assert.equal((await get('/api/notes')).status, 401);
  for (const path of ['/api/chart', '/api/reading', '/api/interpret', '/api/followup', '/api/access/verify']) assert.equal((await post(path, {})).status, 401);
  assert.equal((await post('/api/account/register', { username: 'admin', password: 'test-password-123' })).status, 400);
  assert.equal((await post('/api/account/register', { username: names[0], password: 'short' })).status, 400);
  const users = [];
  for (const name of names) {
    const response = await post('/api/account/register', { username: name, password: 'test-password-123' });
    assert.equal(response.status, 201);
    assert.match(response.headers.getSetCookie()[0], /HttpOnly; SameSite=Strict/);
    const result = await response.json();ids.push(result.user.id);
    assert.deepEqual(Object.keys(result.user).sort(), ['id','username']);
    users.push({ ...result.user, cookie: cookies(response) });
  }
  const [a,b] = users;
  assert.equal((await post('/api/account/register', { username: names[0].toUpperCase(), password: 'test-password-123' })).status, 409);
  assert.equal((await post('/api/account/login', { username: names[0], password: 'wrong-password-123' })).status, 401);
  assert.equal((await post('/api/account/login', { username: names[0], password: 'test-password-123' }, '', { Origin: 'https://evil.example' })).status, 403);
  const [stored] = await store.pool.execute('SELECT password_salt,password_hash FROM users WHERE id=?', [a.id]);
  assert.equal(stored[0].password_hash.length, 64);assert.notEqual(stored[0].password_hash, 'test-password-123');
  // 每日运势：未填生日返回未配置，保存生日后本地计算并规范回读；未登录不可保存档案。
  assert.deepEqual(await (await get('/api/daily-fortune', a.cookie)).json(), { configured: false });
  assert.equal((await post('/api/account/profile', { birthday: 'bad' }, a.cookie)).status, 400);
  assert.equal((await post('/api/account/profile', { birthday: '1800-01-01' }, a.cookie)).status, 400);
  assert.equal((await post('/api/account/profile', { birthday: '1997-05-20', gender: '未知' }, a.cookie)).status, 200);
  assert.equal((await (await get('/api/account/status', a.cookie)).json()).user.birthday, '1997-05-20');
  assert.equal((await (await get('/api/account/status', a.cookie)).json()).user.gender, null);
  const fortune = await (await get('/api/daily-fortune', a.cookie)).json();
  assert.equal(fortune.configured, true);assert.match(fortune.fortune.dayGanZhi, /^[甲乙丙丁戊己庚辛壬癸][子丑寅卯辰巳午未申酉戌亥]$/);
  assert.ok(fortune.fortune.relation && fortune.fortune.luckyColor && fortune.fortune.guidance && fortune.fortune.rules);
  assert.equal((await post('/api/account/profile', { birthday: '1997-05-20', gender: '男' }, a.cookie)).status, 200);
  assert.equal((await (await get('/api/account/status', a.cookie)).json()).user.gender, '男');
  assert.equal((await post('/api/account/profile', { birthday: '2000-01-01' })).status, 401);
  const noteA = await (await post('/api/chart', { tool: 'tarot', question: '用户 A 私人记录', ownerId: b.id }, a.cookie)).json();
  const noteB = await (await post('/api/chart', { tool: 'tarot', question: '用户 B 私人记录' }, b.cookie)).json();
  noteIds.push(noteA.note.id,noteB.note.id);
  assert.deepEqual((await (await get('/api/notes', a.cookie)).json()).notes.map(n=>n.id), [noteA.note.id]);
  assert.deepEqual((await (await get('/api/notes', b.cookie)).json()).notes.map(n=>n.id), [noteB.note.id]);
  assert.equal(await store.get(noteA.note.id, b.id), null);
  await assert.rejects(store.save({ ...noteA.note, answer: '越权修改' }, b.id));
  assert.equal((await post('/api/notes/import', { notes: [noteA.note] }, b.cookie)).status, 400);
  assert.equal((await post('/api/notes/reveal', { id: noteA.note.id, revealed: [0] }, b.cookie)).status, 400);
  assert.equal((await post('/api/notes/delete', { id: noteA.note.id }, b.cookie)).status, 200);
  assert.ok(await store.get(noteA.note.id, a.id));
  const aiA = cookies(await post('/api/access/verify', { code }, a.cookie));
  const aiB = cookies(await post('/api/access/verify', { code }, b.cookie));
  assert.equal((await post('/api/interpret', { record: noteA.record }, `${b.cookie}; ${aiA}`)).status, 401);
  for (const path of ['/api/interpret','/api/followup']) assert.equal((await post(path, { record: noteA.record, question: '越权追问' }, `${b.cookie}; ${aiB}`)).status, 400);
  assert.equal(modelCalls, 0);
  assert.equal((await post('/api/interpret', { record: noteA.record }, `${a.cookie}; ${aiA}`)).status, 200);
  assert.equal(modelCalls, 1);
  assert.equal((await post('/api/notes/clear', { confirm: 'delete-all' }, b.cookie)).status, 200);
  assert.ok(await store.get(noteA.note.id, a.id));assert.equal(await store.get(noteB.note.id, b.id), null);
  // Restarting the account service preserves database-backed user sessions.
  const restarted = new UserAccounts({ pool: store.pool });
  assert.equal((await restarted.current({ headers: { cookie: a.cookie } })).user.id, a.id);
  const legacy = { ...noteA.note, id: randomUUID(), record: { ...noteA.record, id: randomUUID() } };
  noteIds.push(legacy.id);
  await store.pool.execute('INSERT INTO readings (id,note) VALUES (?,?)', [legacy.id, JSON.stringify(legacy)]);
  assert.equal((await store.list(a.id)).some(n=>n.id===legacy.id), false);
  assert.equal((await get('/api/account/legacy', a.cookie)).status, 401);
  const admin = cookies(await post('/api/access/login', { username: 'admin', password: adminPassword }));
  assert.ok((await (await get('/api/account/legacy', admin)).json()).count >= 1);
  assert.equal((await post('/api/account/legacy', { username: names[0] }, admin)).status, 400);
  assert.equal((await post('/api/account/legacy', { username: names[0], confirm: 'assign-legacy' }, admin)).status, 200);
  assert.ok(await store.get(legacy.id, a.id));assert.equal(await store.get(legacy.id, b.id), null);
  const login = await post('/api/account/login', { username: names[0].toUpperCase(), password: 'test-password-123' }, a.cookie);
  assert.equal(login.status, 200);
  const newCookie = cookies(login);
  assert.equal((await get('/api/notes', a.cookie)).status, 401);
  assert.equal((await post('/api/reading', { tool: 'tarot', question: '新会话' }, `${newCookie}; ${aiA}`)).status, 401);
  assert.equal((await post('/api/account/logout', {}, newCookie)).status, 200);
  assert.equal((await get('/api/notes', newCookie)).status, 401);
  assert.equal((await (await get('/api/account/status', newCookie)).json()).user, null);
  assert.equal((await (await get('/api/account/status')).json()).admin, false);
  assert.equal((await (await get('/api/account/status', b.cookie)).json()).admin, false);
  assert.equal((await post('/api/account/login', { username: 'admin', password: 'wrong-password-123' })).status, 401);
  const adminLogin = await post('/api/account/login', { username: 'admin', password: adminPassword }, b.cookie);
  assert.equal(adminLogin.status, 200);assert.equal((await adminLogin.json()).admin, true);
  const adminCookie = cookies(adminLogin);
  const adminStatus = await (await get('/api/account/status', adminCookie)).json();
  assert.equal(adminStatus.admin, true);assert.equal(adminStatus.user, null);
  assert.equal((await get('/api/notes', b.cookie)).status, 401);
  const userLogin = await post('/api/account/login', { username: names[1], password: 'test-password-123', role: 'admin' }, adminCookie);
  assert.equal(userLogin.status, 200);assert.equal((await userLogin.json()).admin, false);
  assert.equal((await (await get('/api/account/status', cookies(userLogin))).json()).admin, false);
  assert.equal((await (await get('/api/account/status', adminCookie)).json()).admin, false);
  assert.equal((await post('/api/access/code', { code: '123456' }, adminCookie)).status, 401);
  const finalAdmin = cookies(await post('/api/account/login', { username: 'admin', password: adminPassword }));
  assert.equal((await post('/api/account/logout', {}, finalAdmin)).status, 200);
  assert.equal((await (await get('/api/account/status', finalAdmin)).json()).admin, false);
});
