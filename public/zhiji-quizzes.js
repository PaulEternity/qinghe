/** 完成全部题目后按所选权重出分，防止缺答被当成零分。 */
export function evaluateZhijiQuiz(quiz, answers) {
  if (!Array.isArray(answers) || answers.length !== quiz.questions.length) return null;
  // 累加每道题被选中的权重，0 分也是有效作答。
  let total = 0;
  for (const [index, [, options]] of quiz.questions.entries()) {
    const choice = answers[index];
    if (!Number.isInteger(choice)) return null;
    const option = options[choice];
    if (!option) return null;
    total += option[1];
  }
  // 归一化到 0～100，供各套题按自己的档位上限输出解读。
  const score = Math.round(total * 100 / (quiz.questions.length * 2));
  const result = quiz.results.find(({max}) => score <= max);
  // 心理年龄以 18～65 岁的娱乐刻度展示，其他主题只输出倾向。
  const age = quiz.id === 'mental-age' ? Math.round(18 + score * 47 / 100) : null;
  return {result, age};
}
